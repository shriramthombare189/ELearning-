package com.learningPlatform.LearningPlatform.Entity;


public class Admindata {

    private Long totalUsers;
    private Long totalCourses;
    private Long totalSellCourses;
    private Long totalFeedback;

    // getters & setters
    public Long getTotalUsers() {
        return totalUsers;
    }

    public void setTotalUsers(Long totalUsers) {
        this.totalUsers = totalUsers;
    }

    public Long getTotalCourses() {
        return totalCourses;
    }

    public void setTotalCourses(Long totalCourses) {
        this.totalCourses = totalCourses;
    }

    public Long getTotalSellCourses() {
        return totalSellCourses;
    }

    public void setTotalSellCourses(Long totalSellCourses) {
        this.totalSellCourses = totalSellCourses;
    }

    public Long getTotalFeedback() {
        return totalFeedback;
    }

    public void setTotalFeedback(Long totalFeedback) {
        this.totalFeedback = totalFeedback;
    }



}
